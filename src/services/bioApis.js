// 3. UniProt (Protein Knowledgebase)
// ==========================================

export async function searchUniprot(query = "ESR2", limit = 10) {
  const trimmed = query.trim();
  if (!trimmed) return [];

  const url = `https://rest.uniprot.org/uniprotkb/search?query=${encodeURIComponent(
    trimmed
  )}+AND+organism_id:9606&format=json&size=${limit}`;

  const response = await fetchWithTimeout(url);
  if (!response.ok) {
    throw new Error(`UniProt API returned HTTP ${response.status}`);
  }

  const data = await response.json();
  const results = data.results || [];

  return results.map(entry => {
    const accession = entry.primaryAccession;
    const entryName = entry.uniProtkbId;
    const proteinName =
      entry.proteinDescription?.recommendedName?.fullName?.value ||
      entry.proteinDescription?.submissionNames?.[0]?.fullName?.value ||
      "Uncharacterized Protein";
    const geneSymbol = entry.genes?.[0]?.geneName?.value || "N/A";
    const length = entry.sequence?.length || 0;

    // Extract function comment if available
    const funcComment = entry.comments?.find(c => c.commentType === "FUNCTION")?.texts?.[0]?.value || "";
    // Extract subcellular location if available
    const locationComment =
      entry.comments
        ?.find(c => c.commentType === "SUBCELLULAR LOCATION")
        ?.subcellularLocations?.map(l => l.location?.value)
        ?.filter(Boolean)
        ?.join(", ") || "";

    return {
      accession,
      entryName,
      proteinName,
      geneSymbol,
      length,
      function: funcComment || "Functional annotation documented in UniProt entry.",
      subcellularLocation: locationComment || "Not explicitly cataloged",
      organism: entry.organism?.scientificName || "Homo sapiens",
      url: `https://www.uniprot.org/uniprotkb/${accession}`,
    };
  });
}

