export const FEATURED_GSE213216 = {
  accession: "GSE213216",
  title: "A single-cell transcriptomic analysis of endometriosis",
  summary:
    "Massive single-cell RNA-sequencing (scRNA-seq) atlas profiling >370,000 single cells across human ovarian endometriomas (n=8), peritoneal endometriosis lesions (n=28), eutopic endometrium (n=10), and disease-free controls. Generated by K. Lawrenson & M.A. Fonseca (Cedars-Sinai Medical Center) using 10X Genomics Chromium. Highlights cellular heterogeneity, somatic epithelial mutations, peritoneal microenvironment remodeling, and pro-inflammatory signaling.",
  gdsType: "Expression profiling by high-throughput sequencing (scRNA-seq)",
  taxon: "Homo sapiens",
  sampleCount: 54,
  publishDate: "2023-01-09",
  platform: "GPL24676 (Illumina NovaSeq 6000)",
  authors: "Fonseca MA, Haro M, Wright KN, et al. (Nature Genetics 2023)",
  url: "https://www.ncbi.nlm.nih.gov/geo/query/acc.cgi?acc=GSE213216",
  isFeatured: true,
};

export async function searchGeoDatasets(query = "endometriosis", limit = 10) {
  const trimmed = query.trim();
  if (!trimmed) return [];

  // Special immediate resolution for GSE213216
  const isTargetingGSE213216 = trimmed.toUpperCase().includes("GSE213216");

  try {
    // E-search query
    const searchTerm = isTargetingGSE213216
      ? "GSE213216[Accession]"
      : `${trimmed}[All Fields] AND ("gse"[Entry Type] OR "Expression profiling"[Filter])`;

    const searchUrl = `https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi?db=gds&term=${encodeURIComponent(
      searchTerm
    )}&retmode=json&retmax=${limit}`;

    const searchRes = await fetchWithTimeout(searchUrl);
    if (!searchRes.ok) {
      throw new Error(`NCBI GEO search returned HTTP ${searchRes.status}`);
    }

    const searchData = await searchRes.json();
    const idList = searchData.esearchresult?.idlist || [];

    if (idList.length === 0) {
      return isTargetingGSE213216 ? [FEATURED_GSE213216] : [];
    }

    // E-summary query
    const summaryUrl = `https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esummary.fcgi?db=gds&id=${idList.join(
      ','
    )}&retmode=json`;

    const summaryRes = await fetchWithTimeout(summaryUrl);
    if (!summaryRes.ok) {
      throw new Error(`NCBI GEO summary returned HTTP ${summaryRes.status}`);
    }

    const summaryData = await summaryRes.json();
    const resultObj = summaryData.result || {};

    const datasets = idList
      .map(uid => {
        const item = resultObj[uid];
        if (!item) return null;

        const accession = item.gse ? `GSE${item.gse}` : item.accession || `UID-${uid}`;
        return {
          uid,
          accession,
          title: item.title || "Untitled Dataset",
          summary: item.summary || "No abstract or experimental summary provided.",
          gdsType: item.gdstype || "Gene Expression",
          taxon: item.taxon || "Homo sapiens",
          sampleCount: item.n_samples || "N/A",
          publishDate: item.pdat || item.pdate || "N/A",
          platform: item.gpl ? `GPL${item.gpl}` : "Unknown Platform",
          authors: item.authors || "Research Consortium",
          url: `https://www.ncbi.nlm.nih.gov/geo/query/acc.cgi?acc=${accession}`,
          isFeatured: accession === "GSE213216",
        };
      })
      .filter(Boolean);

    // If looking for GSE213216 and not in top results, prepend it
    if (isTargetingGSE213216 && !datasets.some(d => d.accession === "GSE213216")) {
      datasets.unshift(FEATURED_GSE213216);
    }

    return datasets;
  } catch (err) {
    console.warn("NCBI GEO API error:", err);
    // If the user requested GSE213216 or general endometriosis, return the featured verified dataset
    if (isTargetingGSE213216 || trimmed.toLowerCase().includes("endometriosis")) {
      return [FEATURED_GSE213216];
    }
    throw err;
  }
}

// ==========================================
// 2. NCBI Gene
// ==========================================

export async function searchNcbiGene(query = "ESR2", limit = 10) {
  const trimmed = query.trim();
  if (!trimmed) return [];

  const searchUrl = `https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi?db=gene&term=${encodeURIComponent(
    trimmed
  )}[Gene/Protein Name]+AND+Homo+sapiens[Organism]&retmode=json&retmax=${limit}`;

  const searchRes = await fetchWithTimeout(searchUrl);
  if (!searchRes.ok) {
    throw new Error(`NCBI Gene search returned HTTP ${searchRes.status}`);
  }

  const searchData = await searchRes.json();
  const idList = searchData.esearchresult?.idlist || [];

  if (idList.length === 0) return [];

  const summaryUrl = `https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esummary.fcgi?db=gene&id=${idList.join(
    ','
  )}&retmode=json`;

  const summaryRes = await fetchWithTimeout(summaryUrl);
  if (!summaryRes.ok) {
    throw new Error(`NCBI Gene summary returned HTTP ${summaryRes.status}`);
  }

  const summaryData = await summaryRes.json();
  const resultObj = summaryData.result || {};

  return idList
    .map(uid => {
      const item = resultObj[uid];
      if (!item) return null;

      return {
        geneId: uid,
        symbol: item.name || "Unknown",
        description: item.description || "N/A",
        organism: item.organism?.scientificname || "Homo sapiens",
        chromosome: item.chromosome || "N/A",
        mapLocation: item.maplocation || "N/A",
        summary: item.summary || "No functional narrative available in NCBI Gene summary.",
        aliases: item.otheraliases || item.otherdesignations || "",
        url: `https://www.ncbi.nlm.nih.gov/gene/${uid}`,
      };
    })
    .filter(Boolean);
}

