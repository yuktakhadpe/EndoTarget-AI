// 5. ChEMBL (Bioactivities, Targets & Drugs)
// ==========================================

export async function searchChembl(query = "ESR2", limit = 10) {
  const trimmed = query.trim();
  if (!trimmed) return { targets: [], molecules: [] };

  const targetUrl = `https://www.ebi.ac.uk/chembl/api/data/target/search?q=${encodeURIComponent(
    trimmed
  )}&format=json&limit=${limit}`;

  const moleculeUrl = `https://www.ebi.ac.uk/chembl/api/data/molecule/search?q=${encodeURIComponent(
    trimmed
  )}&format=json&limit=${limit}`;

  const [targetRes, molRes] = await Promise.allSettled([
    fetchWithTimeout(targetUrl),
    fetchWithTimeout(moleculeUrl),
  ]);

  let targets = [];
  if (targetRes.status === "fulfilled" && targetRes.value.ok) {
    const data = await targetRes.value.json();
    targets = (data.targets || []).map(t => ({
      targetChemblId: t.target_chembl_id,
      prefName: t.pref_name || "Target",
      targetType: t.target_type || "Protein",
      organism: t.organism || "Homo sapiens",
      score: t.score,
      url: `https://www.ebi.ac.uk/chembl/target_report_card/${t.target_chembl_id}/`,
    }));
  }

  let molecules = [];
  if (molRes.status === "fulfilled" && molRes.value.ok) {
    const data = await molRes.value.json();
    molecules = (data.molecules || []).map(m => ({
      moleculeChemblId: m.molecule_chembl_id,
      prefName: m.pref_name || m.molecule_chembl_id,
      maxPhase: m.max_phase != null ? `Phase ${m.max_phase}` : "Preclinical / Exploratory",
      moleculeType: m.molecule_type || "Small molecule",
      firstApproval: m.first_approval || "N/A",
      structureSmiles: m.molecule_structures?.canonical_smiles || null,
      url: `https://www.ebi.ac.uk/chembl/compound_report_card/${m.molecule_chembl_id}/`,
    }));
  }

  return { targets, molecules };
}

