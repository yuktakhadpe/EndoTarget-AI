// 4. STRING (Protein-Protein Interactions)
// ==========================================

export async function fetchStringInteractions(geneSymbol = "ESR2", limit = 15) {
  const trimmed = geneSymbol.trim();
  if (!trimmed) return [];

  const apiUrl = `https://string-db.org/api/json/interaction_partners?identifiers=${encodeURIComponent(
    trimmed
  )}&species=9606&limit=${limit}`;

  const response = await fetchWithTimeout(apiUrl);
  if (!response.ok) {
    throw new Error(`STRING API returned HTTP ${response.status}`);
  }

  const data = await response.json();
  if (!Array.isArray(data)) return [];

  return data.map(item => ({
    queryGene: item.preferredName_A || trimmed,
    partnerGene: item.preferredName_B || "Interacting Partner",
    stringIdA: item.stringId_A,
    stringIdB: item.stringId_B,
    combinedScore: (item.score * 100).toFixed(0),
    experimentalScore: (item.escore * 100).toFixed(0),
    databaseScore: (item.dscore * 100).toFixed(0),
    coexpressionScore: (item.ascore * 100).toFixed(0),
    textminingScore: (item.tscore * 100).toFixed(0),
    networkUrl: `https://string-db.org/network/${encodeURIComponent(item.preferredName_B || trimmed)}`,
  }));
}

export function getStringEmbedUrl(geneSymbol = "ESR2") {
  return `https://string-db.org/api/svg/network?identifiers=${encodeURIComponent(
    geneSymbol.trim()
  )}&species=9606&network_flavor=confidence`;
}

