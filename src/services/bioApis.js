/**
 * BioAPIs Service Layer
 * Direct, keyless, CORS-enabled client integrations for public biological databases:
 * - NCBI GEO (Gene Expression Datasets)
 * - NCBI Gene (Gene Annotations)
 * - UniProt (Protein Information & Sequences)
 * - STRING (Protein-Protein Interaction Networks)
 * - ChEMBL (Target & Molecule Bioactivities)
 * - GWAS Catalog (Genetic Associations & Risk Loci)
 */

const TIMEOUT_MS = 12000;

/**
 * Fetch wrapper with timeout handling
 */
async function fetchWithTimeout(url, options = {}, timeout = TIMEOUT_MS) {
  const controller = new AbortController();
  const id = setTimeout(() => controller.abort(), timeout);
  try {
    const response = await fetch(url, {
      ...options,
      signal: controller.signal,
    });
    clearTimeout(id);
    return response;
  } catch (error) {
    clearTimeout(id);
    if (error.name === 'AbortError') {
      throw new Error(`Request timed out after ${timeout / 1000} seconds. The public server may be experiencing high load.`);
    }
    throw error;
  }
}

